function placeText(province, city, county) {
  const parts = []
  ;[province, city, county].forEach((name) => {
    if (name && parts.indexOf(name) < 0) parts.push(name)
  })
  return parts.join(' · ')
}

function gasOf(province, city, county) {
  const exact = COUNTY_GAS[province + '/' + city + '/' + county]
  if (exact) return exact
  const row = countyRows(province, city).find((item) => item.name === county)
  if (row && row.urban) return URBAN_GAS[province + '/' + city] || null
  return null
}

function present(province, city, county) {
  if (countiesOf(province, city).indexOf(county) < 0) {
    province = '贵州'
    city = '毕节'
    county = '七星关'
    if (countiesOf(province, city).indexOf(county) < 0) {
      province = '北京'
      city = '北京'
      county = countiesOf(province, city)[0] || ''
    }
  }
  return {
    province,
    city,
    county,
    provinceIndex: PROVINCE_NAMES.indexOf(province),
    cityIndex: citiesOf(province).indexOf(city),
    countyIndex: countiesOf(province, city).indexOf(county),
    place: placeText(province, city, county),
    elec: ELEC_CITY[city] || ELEC_CITY[county] || ELEC[province] || null,
    gas: gasOf(province, city, county)
  }
}

function searchCities(keyword) {
  const text = String(keyword || '').replace(/\s/g, '').replace(/(市|县|区)$/, '')
  if (!text) return []
  const out = []
  REGIONS.forEach((row) => {
    const hitProvince = text.length >= 2 && row.name.indexOf(text) >= 0
    row.cities.forEach((city) => {
      const hitCity = city.name.indexOf(text) >= 0
      city.counties.forEach((county) => {
        if (county.name.indexOf(text) >= 0 || hitCity || hitProvince) {
          const exact = county.name === text ? 0 : (city.name === text ? 1 : 2)
        out.push({
            province: row.name,
            city: city.name,
            county: county.name,
            place: placeText(row.name, city.name, county.name),
            exact
          })
        }
      })
    })
  })
  out.sort((a, b) => a.exact - b.exact)
  return out.slice(0, 40)
}


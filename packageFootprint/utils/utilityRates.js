function shortProvince(name) {
  return String(name || '')
    .replace('维吾尔自治区', '')
    .replace('壮族自治区', '')
    .replace('回族自治区', '')
    .replace('自治区', '')
    .replace('特别行政区', '')
    .replace(/省$/, '')
    .replace(/市$/, '')
}

function shortPlace(name) {
  return String(name || '').replace(/(特别行政区|自治县|自治旗|自治州|地区|盟|林区|新区|市|县|区|旗)$/, '')
}

function buildRegions() {
  return Object.keys(PCA).map((pname) => {
    const province = shortProvince(pname)
    const cities = []
    Object.keys(PCA[pname] || {}).forEach((cname) => {
      const rawList = PCA[pname][cname] || []
      if (!rawList.length) return
      let city = shortPlace(cname)
      if (cname === '市辖区' || cname === '县') city = province
      else if (cname.indexOf('直辖') >= 0) city = '省直辖'
      const counties = rawList.map((raw) => ({
        name: shortPlace(raw) || raw,
        urban: /区$/.test(raw)
      }))
      const existing = cities.find((item) => item.name === city)
      if (existing) existing.counties = existing.counties.concat(counties)
      else cities.push({ name: city, counties })
    })
    if (province === '贵州') {
      const bijie = cities.find((item) => item.name === '毕节')
      if (bijie && !bijie.counties.some((item) => item.name === '百里杜鹃')) {
        bijie.counties.push({ name: '百里杜鹃', urban: false })
      }
    }
    return { name: province, cities }
  })
}

const REGIONS = buildRegions()
const PROVINCE_NAMES = REGIONS.map((item) => item.name)

function regionOf(province) {
  return REGIONS.find((item) => item.name === province) || null
}

function citiesOf(province) {
  const row = regionOf(province)
  return row ? row.cities.map((item) => item.name) : []
}

function countyRows(province, city) {
  const row = regionOf(province)
  if (!row) return []
  const found = row.cities.find((item) => item.name === city)
  return found ? found.counties : []
}

function countiesOf(province, city) {
  return countyRows(province, city).map((item) => item.name)
}


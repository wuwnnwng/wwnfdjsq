function elec(cycle, ranges, prices, note) {
  const tiers = []
  const names = ['第一档', '第二档', '第三档']
  for (let i = 0; i < prices.length; i++) {
    if (!prices[i]) continue
    tiers.push({ name: names[i] || ('第' + (i + 1) + '档'), range: ranges[i] || '分档电量见当地公示', price: prices[i] })
  }
  return { cycle, tiers, note: note || '本省居民一户一表参考价，不满1千伏。同省城市电价相同。' }
}

function gas(prices, note, ranges) {
  const tiers = []
  const names = ['第一档', '第二档', '第三档']
  for (let i = 0; i < prices.length; i++) {
    if (!prices[i]) continue
    tiers.push({
      name: names[i],
      range: (ranges && ranges[i]) || '分档气量见当地公示',
      price: prices[i]
    })
  }
  return { cycle: '居民管道天然气', tiers, note: note || MYSTEEL }
}


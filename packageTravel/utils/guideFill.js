function hash(text) {
  let value = 0
  for (let i = 0; i < text.length; i += 1) value = (value * 33 + text.charCodeAt(i)) >>> 0
  return value
}

function take(list, seed, count) {
  const pool = []
  list.forEach((item) => {
    if (item && pool.indexOf(item) < 0) pool.push(item)
  })
  if (!pool.length) return []
  const size = Math.min(count, pool.length)
  const start = hash(seed) % pool.length
  const out = []
  for (let i = 0; i < pool.length && out.length < size; i += 1) out.push(pool[(start + i) % pool.length])
  return out
}

function tokensOf(name) {
  const short = shortName(name)
  return short.length >= 2 ? [short] : []
}

function claimedBy(item, names) {
  for (let i = 0; i < names.length; i += 1) {
    const tokens = tokensOf(names[i])
    for (let j = 0; j < tokens.length; j += 1) {
      if (item.indexOf(tokens[j]) >= 0) return names[i]
    }
    const head = shortName(names[i])
    if (head.length === 1 && item.indexOf(head + '县') >= 0) return names[i]
  }
  return ''
}

function packOf(cityCode) {
  if (PACK[cityCode]) return PACK[cityCode]
  const foods = index.cityFood[cityCode] || []
  const sights = index.citySight[cityCode] || []
  if (!foods.length && !sights.length) return null
  return { foods, sights }
}

function fillCity(cityCode) {
  const pack = PACK[cityCode]
  if (!pack) return { foods: [], sights: [] }
  return { foods: pack.foods.slice(0, 8), sights: pack.sights.slice(0, 8) }
}

function fillCounty(place) {
  const key = `${place.provinceId}|${place.name}`
  const pack = packOf(place.cityCode) || { foods: [], sights: [] }
  const names = index.places.filter((row) => row[2] === place.cityCode).map((row) => row[1])
  const ownFoods = pack.foods.filter((item) => claimedBy(item, [place.name]) === place.name)
  const sharedFoods = pack.foods.filter((item) => !claimedBy(item, names))
  const ownSights = pack.sights.filter((item) => claimedBy(item, [place.name]) === place.name)
  const sharedSights = pack.sights.filter((item) => !claimedBy(item, names))
  const alias = ALIAS[key] || []
  const foodPool = ownFoods.concat(sharedFoods)
  const sightPool = ownSights.concat(sharedSights)
  const foods = take(foodPool, place.id, 4)
  const sights = alias.length ? alias.slice(0, 4) : take(sightPool, `${place.id}s`, 4)
  return { foods, sights }
}


function placeWord(name) {
  return String(name || '').replace(/(特别行政区|自治县|自治旗|林区|市|县|旗)$/, '') || name || '当地'
}

function byRule(rules, place, name) {
  for (let i = 0; i < rules.length; i += 1) {
    if (rules[i][0].test(name)) return `${name}是${place}人认得的名字。${rules[i][1]}`
  }
  return ''
}

function introOf(kind, name, cityName) {
  const place = placeWord(cityName)
  if (KNOWN[name]) return KNOWN[name]
  if (kind === 'food') {
    return byRule(FOOD_RULES, place, name) || `${name}是${place}吃了很久的地方味道。早先多在家里和赶集时做，用来待客、过节，做法跟着本地出产慢慢固定下来。`
  }
  return byRule(SIGHT_RULES, place, name) || `${name}是${place}常去的地方。它和这里的居住、赶集或祭祀连在一起，不是临时起的名字。`
}


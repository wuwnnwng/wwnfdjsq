const GBK_MAP = Object.create(null)
;(function buildMap() {
  for (let i = 0; i < GB2312_L1.length; i += 1) {
    const qu = 16 + Math.floor(i / 94)
    const wei = (i % 94) + 1
    GBK_MAP[GB2312_L1.charAt(i)] = [0xa0 + qu, 0xa0 + wei]
  }
  Object.keys(EXTRA).forEach((ch) => {
    GBK_MAP[ch] = EXTRA[ch]
  })
  Object.keys(OVERRIDE).forEach((ch) => {
    GBK_MAP[ch] = OVERRIDE[ch]
  })
})()

function encodeGbkChar(ch) {
  const code = ch.charCodeAt(0)
  if (code < 0x80) return [code]
  if (code >= 0xff01 && code <= 0xff5e) {
    const gbk = 0xa3a1 + (code - 0xff01)
    return [gbk >> 8, gbk & 0xff]
  }
  const mapped = GBK_MAP[ch]
  return mapped ? mapped.slice() : null
}

function toGbkBytes(text) {
  const str = String(text || '')
  const bytes = []
  for (let i = 0; i < str.length; i += 1) {
    const code = str.charCodeAt(i)
    if (code >= 0xd800 && code <= 0xdbff) return null
    const encoded = encodeGbkChar(str.charAt(i))
    if (!encoded) return null
    for (let j = 0; j < encoded.length; j += 1) bytes.push(encoded[j])
  }
  return bytes
}

function canEncodeGbk(text) {
  return !!toGbkBytes(text)
}

